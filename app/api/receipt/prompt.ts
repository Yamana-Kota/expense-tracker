/**
 * レシート解析プロンプトを生成する
 *
 * Geminiに渡すプロンプト文字列を返す。今日の日付を含めることで、
 * レシートに日付が記載されていない場合のフォールバックに使用する。
 * プロンプトの調整は BASE_PROMPT を編集して行う。
 *
 * @param todayDate - 今日の日付（YYYY-MM-DD形式）
 * @returns Geminiに渡すプロンプト文字列
 */
export function buildReceiptPrompt(todayDate: string): string {
  return `${BASE_PROMPT}\n\n今日の日付: ${todayDate}`;
}

// ----------------------------------------
// Helpers
// ----------------------------------------

const BASE_PROMPT = `レシートや領収書の画像を解析して、家計簿への記録に必要な情報をJSON配列で返してください。

## 処理手順

1. レシート上部から店舗名を推測・抽出する（例：業務スーパー、オーケー、セブンイレブン、イオンなど）
2. レシート内の全品目を一つずつ確認し、それぞれ個別にカテゴリ分類する
3. 各品目を配列の要素として1つずつまとめる（同じカテゴリでもまとめない）

## 各要素のフィールド

- date: 日付（YYYY-MM-DD形式。レシートに記載がない場合は今日の日付を使用）
- type: 種別（"expense"=支出 または "income"=収入。レシートはほぼ支出）
- category: カテゴリ（下記リストから最も近いものを選択）
- amount: 品目の税込金額（整数・円単位）
- note: 「商品名（店舗名）」の形式で記載する。商品名はレシートの品目名を元に、一般的な日本語名称（カタカナではなく漢字・ひらがな混じりの自然な表記）に変換する（例：「トマト」→「トマト」、「ニンジン」→「にんじん」、「ギュウニュウ」→「牛乳」）。店舗名が不明な場合は「商品名」のみ記載

## カテゴリリスト

支出（type="expense"）: 食費, 外食, 交通費, 娯楽, 日用品, 医療, 衣服, その他
収入（type="income"）: 給与, 副業, ボーナス, 贈り物, その他

## 分類ヒント（日本のレシート向け汎用ルール）

日本のレシートでは、品目名の横に「※」「軽」「F」などのマークがついているものは軽減税率対象（8%）であり、原則として「食費」です。マークがついていないもの（標準税率10%）は、洗剤や雑貨などの「日用品」や「その他」に分類される可能性が高いです。このルールを分類の基準にしてください。

## 出力形式（JSONのみ返答。説明文や\`\`\`は不要）

[
  {
    "date": "YYYY-MM-DD",
    "type": "expense" または "income",
    "category": "カテゴリ名",
    "amount": 数値（整数）,
    "note": "商品名（店舗名）"
  }
]`;
